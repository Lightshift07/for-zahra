/**
 * Vite plugin: offline support + automatic updates (no dependencies).
 *
 * At build time it:
 *   1. picks a version id (the git commit on GitHub Actions, otherwise a timestamp)
 *      and exposes it to the app as __APP_VERSION__;
 *   2. writes `version.json` → { "version": "<id>" }, which the app polls to
 *      notice a newer deploy (see src/lib/autoUpdate.ts);
 *   3. writes `sw.js`, a service worker that precaches every built file
 *      (pages, code, styles, icons, letter photos + voice notes) so the site
 *      opens with no signal, and always fetches a fresh page when online.
 */
import { readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import type { Plugin } from 'vite'

const NEVER_CACHE = new Set(['_headers', 'robots.txt', 'version.json', 'sw.js'])

function listFiles(dir: string, root = dir): string[] {
  let out: string[] = []
  for (const name of readdirSync(dir)) {
    const full = join(dir, name)
    if (statSync(full).isDirectory()) out = out.concat(listFiles(full, root))
    else out.push(relative(root, full).split('\\').join('/'))
  }
  return out
}

export function offline(): Plugin {
  const version = (process.env.GITHUB_SHA?.slice(0, 12) ?? Date.now().toString(36)).toString()
  let publicDir = ''
  let isBuild = false

  return {
    name: 'offline',
    config() {
      return { define: { __APP_VERSION__: JSON.stringify(version) } }
    },
    configResolved(config) {
      publicDir = config.publicDir
      isBuild = config.command === 'build'
    },
    generateBundle(_options, bundle) {
      if (!isBuild) return
      const files = new Set<string>(['', 'index.html'])
      for (const fileName of Object.keys(bundle)) files.add(fileName)
      if (publicDir) for (const f of listFiles(publicDir)) files.add(f)
      const precache = [...files].filter((f) => !NEVER_CACHE.has(f)).sort()

      this.emitFile({ type: 'asset', fileName: 'version.json', source: JSON.stringify({ version }) + '\n' })
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(version, precache) })
    },
  }
}

function serviceWorker(version: string, files: string[]): string {
  return `// Generated by vite/offline.ts — do not edit.
const VERSION = ${JSON.stringify(version)};
const PRECACHE = 'for-zahra-' + VERSION;
const RUNTIME = 'for-zahra-runtime';
const FILES = ${JSON.stringify(files)};
const scope = self.registration.scope;
const INDEX = new URL('index.html', scope).href;
const NAV_TIMEOUT_MS = 4000;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(PRECACHE)
      .then((cache) => cache.addAll(FILES.map((f) => new Request(new URL(f, scope).href, { cache: 'reload' }))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('for-zahra-') && k !== PRECACHE && k !== RUNTIME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  // The page itself: always try the network first (revalidating past the HTTP cache).
  // Offline, or no answer within NAV_TIMEOUT_MS (weak signal), → the saved copy;
  // the app's version check then picks up anything newer once the network catches up.
  if (req.mode === 'navigate') {
    const saved = () => caches.match(INDEX, { ignoreSearch: true }).then((hit) => hit || caches.match(scope));
    const network = fetch(req.url, { cache: 'no-cache', credentials: 'same-origin' }).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(PRECACHE).then((c) => c.put(INDEX, copy)); }
      return res;
    });
    const slow = new Promise((resolve) => setTimeout(resolve, NAV_TIMEOUT_MS)).then(saved);
    event.respondWith(
      Promise.race([network.catch(() => saved()), slow.then((hit) => hit || network)])
        .then((res) => res || network),
    );
    return;
  }

  // Version checks always go to the network.
  if (url.pathname.endsWith('/version.json') || url.pathname.endsWith('/sw.js')) return;

  // Google Fonts: serve the saved copy, refresh it in the background.
  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    event.respondWith(
      caches.open(RUNTIME).then((cache) =>
        cache.match(req).then((hit) => {
          const fresh = fetch(req).then((res) => { if (res.ok || res.type === 'opaque') cache.put(req, res.clone()); return res; });
          return hit || fresh;
        }),
      ),
    );
    return;
  }

  // Our own files (hashed, never change): saved copy first, network otherwise.
  if (url.origin === self.location.origin) {
    event.respondWith(
      caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(RUNTIME).then((c) => c.put(req, copy)); }
        return res;
      })),
    );
  }
});
`
}
